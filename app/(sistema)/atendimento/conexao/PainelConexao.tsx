'use client';

import { useEffect, useState, useTransition } from 'react';
import { CheckCircle2, LoaderCircle, QrCode, Smartphone } from 'lucide-react';
import type { StatusWhatsApp } from '@/lib/whatsapp/tipos';
import { conectarWhatsApp, desconectarWhatsApp } from './actions';

const nomes: Record<StatusWhatsApp['status'], string> = {
  desconectado: 'Desconectado', iniciando: 'Preparando conexão', qr: 'Pronto para escanear',
  autenticando: 'Sincronizando com o celular', conectado: 'WhatsApp conectado',
  encerrando: 'Desconectando', erro: 'Conexão interrompida', indisponivel: 'Serviço indisponível',
};

export default function PainelConexao() {
  const [estado, setEstado] = useState<StatusWhatsApp | null>(null);
  const [erro, setErro] = useState('');
  const [confirmarSaida, setConfirmarSaida] = useState(false);
  const [pendente, startTransition] = useTransition();
  useEffect(() => {
    let cancelado = false;
    let timer: ReturnType<typeof setTimeout>;
    const controller = new AbortController();
    async function atualizar() {
      try {
        const resposta = await fetch('/api/whatsapp/status', { cache: 'no-store', signal: controller.signal });
        if (resposta.status === 401 || resposta.status === 403) {
          if (!cancelado) { setEstado(null); setErro('Sua sessão não permite acessar a conexão. Entre novamente como administrador.'); }
          return;
        }
        const dados = await resposta.json();
        if (cancelado) return;
        if (resposta.ok || resposta.status === 503) { setEstado(dados); }
        else throw new Error('Falha na consulta');
      } catch {
        if (!cancelado) setEstado({ status: 'indisponivel', qr: null, numero: null, mensagem: 'Não foi possível consultar a conexão. Tentando novamente…', atualizadoEm: new Date().toISOString() });
      }
      if (!cancelado) timer = setTimeout(atualizar, 2500);
    }
    void atualizar();
    return () => { cancelado = true; clearTimeout(timer); controller.abort(); };
  }, []);

  function executar(desconectar = false) {
    setErro('');
    setConfirmarSaida(false);
    startTransition(async () => {
      try {
        const resultado = await (desconectar ? desconectarWhatsApp() : conectarWhatsApp());
        if (!resultado.sucesso) setErro(resultado.mensagem);
        else setEstado({ status: desconectar ? 'encerrando' : 'iniciando', qr: null, numero: null, mensagem: null, atualizadoEm: new Date().toISOString() });
      } catch { setErro('Não foi possível executar a operação. Verifique sua sessão e tente novamente.'); }
    });
  }
  const conectado = estado?.status === 'conectado';
  const aguardando = estado && ['iniciando', 'autenticando', 'encerrando'].includes(estado.status);
  const podeConectar = estado && ['desconectado', 'erro'].includes(estado.status);

  return <div className="mt-8 grid gap-6 md:grid-cols-[1.1fr_1fr]">
    <section className="rounded-2xl border border-slate-200 bg-white p-6 shadow-sm sm:p-8">
      <div className="flex items-center justify-between gap-3">
        <h2 className="font-semibold text-slate-800">Conexão da empresa</h2>
        <span className={`rounded-full px-3 py-1 text-xs font-semibold ${conectado ? 'bg-emerald-100 text-emerald-800' : 'bg-slate-100 text-slate-600'}`}>{estado ? nomes[estado.status] : 'Consultando…'}</span>
      </div>
      <div className="my-6 flex min-h-80 flex-col items-center justify-center rounded-xl border border-slate-100 bg-slate-50 p-3 text-center">
        {estado?.qr ? <>
          {/* QR is generated by the private bridge and must not pass through an image cache. */}
          {/* eslint-disable-next-line @next/next/no-img-element */}
          <img src={estado.qr} width={320} height={320} alt="QR Code para vincular o WhatsApp da empresa" className="h-auto w-full max-w-80 rounded-lg" />
          <p className="mt-3 text-xs text-slate-500">O código é atualizado automaticamente.</p>
        </> : conectado ? <>
          <CheckCircle2 className="mb-4 size-16 text-emerald-600" />
          <p className="text-lg font-semibold text-emerald-900">Aparelho conectado</p>
          {estado.numero && <p className="mt-2 text-slate-600">+{estado.numero}</p>}
        </> : aguardando || !estado ? <>
          <LoaderCircle className="mb-4 size-12 animate-spin text-slate-400" />
          <p className="text-sm text-slate-600">{estado?.status === 'autenticando' ? 'Aguarde a confirmação do WhatsApp…' : 'Preparando a conexão…'}</p>
        </> : <>
          <QrCode className="mb-4 size-16 text-slate-300" />
          <p className="max-w-64 text-sm text-slate-500">{estado.status === 'qr' ? 'Aguardando um novo código…' : 'Clique em gerar QR Code para conectar o celular da empresa.'}</p>
        </>}
      </div>
      {podeConectar && <button disabled={pendente} onClick={() => executar()} className="w-full rounded-xl bg-emerald-700 px-4 py-3 font-semibold text-white hover:bg-emerald-800 disabled:opacity-50">{pendente ? 'Iniciando…' : 'Gerar QR Code'}</button>}
      {conectado && !confirmarSaida && <button onClick={() => setConfirmarSaida(true)} className="w-full rounded-xl border border-slate-300 px-4 py-3 text-sm font-semibold">Desconectar este aparelho</button>}
      {confirmarSaida && <div className="rounded-lg bg-amber-50 p-4 text-sm"><p>Encerrar a conexão deste sistema com o WhatsApp da empresa?</p>
        <div className="mt-3 flex gap-4"><button disabled={pendente} onClick={() => executar(true)} className="font-semibold text-red-700">Sim, desconectar</button><button onClick={() => setConfirmarSaida(false)}>Cancelar</button></div></div>}
      {(erro || estado?.mensagem) && <p role="status" className="mt-4 text-sm text-amber-800">{erro || estado?.mensagem}</p>}
    </section>
    <aside className="space-y-5">
      <section className="rounded-2xl border border-slate-200 bg-white p-6 sm:p-8">
        <Smartphone className="mb-4 size-7 text-emerald-700" />
        <h2 className="text-lg font-semibold text-[#0A2540]">No celular da empresa</h2>
        <ol className="mt-5 list-decimal space-y-4 pl-5 text-sm leading-relaxed text-slate-600">
          <li>Abra o WhatsApp que você deseja conectar.</li>
          <li>Entre em <strong>Aparelhos conectados</strong>, nas configurações ou no menu de três pontos.</li>
          <li>Toque em <strong>Conectar um aparelho</strong>.</li>
          <li>Aponte a câmera para o QR Code e aguarde a confirmação nesta tela.</li>
        </ol>
      </section>
      <section className="rounded-2xl bg-[#0A2540] p-6 text-white">
        <h2 className="font-semibold">Mantenha este computador ligado</h2>
        <p className="mt-3 text-sm leading-relaxed text-slate-300">A conexão funciona pelo serviço instalado neste computador. A sessão é salva para reconectar ao reiniciar o serviço.</p>
        <p className="mt-3 text-sm leading-relaxed text-slate-300">Com o aparelho conectado, abra um cliente em Atendimento para visualizar e enviar mensagens e anexos. As respostas automáticas ainda não estão ativas.</p>
      </section>
      <p className="px-1 text-xs leading-relaxed text-slate-500">Conexão via WhatsApp Web, usando uma integração não oficial. A conexão pode exigir novo pareamento quando o WhatsApp mudar.</p>
    </aside>
  </div>;
}
